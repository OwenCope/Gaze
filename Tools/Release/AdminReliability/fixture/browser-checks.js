(async () => {
  const checks=[];
  const check=(condition,message)=>{if(!condition)throw new Error(message);checks.push(message);};
  const settle=()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
  const waitClosed=async()=>{const deadline=performance.now()+3000;while(document.querySelector('[role="dialog"]')&&performance.now()<deadline)await settle();};
  const button=(root,text)=>[...root.querySelectorAll('button')].find(b=>b.textContent.trim()===text);
  const dialog=()=>document.querySelector('[role="dialog"]');
  const type=async(input,text)=>{
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,text);
    input.dispatchEvent(new Event('input',{bubbles:true}));await settle();
  };
  const api=window.__admin;
  const settings=document.getElementById('settings-fixture'),toggle=settings.querySelector('input');
  toggle.click();toggle.click();await settle();
  check(api.calls.length===1&&api.pending.length===1,'Settings: duplicate clicks send one request');
  check(toggle.checked&&toggle.disabled,'Settings: pending value visible and disabled');
  api.reply(502,'<html>synthetic outage</html>',true);await settle();
  check(!toggle.checked&&!toggle.disabled&&settings.querySelector('[role="alert"]').textContent.includes('HTTP 502'),'Settings: non-JSON failure rolls back with an error');
  toggle.click();await settle();api.reply(200,{ok:true});await settle();
  check(!toggle.checked&&settings.querySelector('[role="alert"]').textContent.includes('could not be confirmed'),'Settings: malformed success never marks saved');
  toggle.click();await settle();api.reply(200,{releasesRequireSignIn:true});await settle();
  check(toggle.checked&&settings.querySelector('[role="status"]').textContent==='Saved','Settings: acknowledged value is saved');

  const testers=document.getElementById('testers-fixture');
  testers.querySelector('ul button').click();await settle();
  button(dialog(),'Reviewer').click();await settle();
  check(button(dialog(),'Reviewer').getAttribute('aria-pressed')==='true','Tester roles: pending selection responds immediately');
  api.reply(503,{error:'Synthetic save failure'});await settle();
  check(button(dialog(),'Reviewer').getAttribute('aria-pressed')==='false'&&dialog().querySelector('[role="alert"]'),'Tester roles: failure restores the prior selection and shows an alert');
  let count=api.calls.length;api.confirmNext=false;button(dialog(),'Remove').click();await settle();
  check(api.calls.length===count,'Tester removal: cancellation sends nothing');
  api.confirmNext=true;button(dialog(),'Remove').click();button(dialog(),'Remove').click();await settle();
  check(api.calls.length===count+1&&api.pending.length===1,'Tester removal: duplicate activation sends one request');
  api.reply(200,'<html>unexpected sign-in page</html>',true);await settle();
  check(dialog()&&testers.querySelectorAll('ul li').length===1&&dialog().querySelector('[role="alert"]'),'Tester removal: unconfirmed response keeps the profile');
  button(dialog(),'Remove').click();await settle();api.reply(200,[]);await settle();
  await waitClosed();
  check(!dialog()&&!testers.querySelector('ul'),'Tester removal: confirmed response updates the list');
  button(testers,'Add someone').click();await settle();
  await type(document.getElementById('tester-email'),'new@example.test');
  await type(document.getElementById('tester-note'),'Keep this draft');
  let form=dialog().querySelector('form');count=api.calls.length;form.requestSubmit();form.requestSubmit();await settle();
  check(api.calls.length===count+1&&document.getElementById('tester-email').matches(':disabled'),'Add tester: Enter/form submit is serialized and fields freeze');
  api.fail();await settle();
  check(document.getElementById('tester-email').value==='new@example.test'&&document.getElementById('tester-note').value==='Keep this draft'&&dialog().querySelector('[role="alert"]'),'Add tester: network failure preserves all draft fields');
  form.requestSubmit();await settle();api.reply(200,{ok:true});await settle();
  check(dialog()&&document.getElementById('tester-note').value==='Keep this draft','Add tester: malformed success keeps the draft');
  form.requestSubmit();await settle();api.reply(200,[{email:'new@example.test',note:'Keep this draft',roles:['tester'],addedAt:'2026-01-01'}]);await settle();await waitClosed();
  check(!dialog()&&testers.querySelectorAll('ul li').length===1,'Add tester: confirmed response closes the form and updates the list');

  const roles=document.getElementById('roles-fixture');
  roles.querySelector('[aria-label="New role"]').click();await settle();
  await type(document.getElementById('role-name'),'Auditor');
  await type(dialog().querySelector('[aria-label="Hex"]'),'007AFF');
  dialog().querySelector('input[type="checkbox"]').click();await settle();
  form=dialog().querySelector('form');count=api.calls.length;form.requestSubmit();form.requestSubmit();await settle();
  check(api.calls.length===count+1&&document.getElementById('role-name').matches(':disabled'),'Roles: duplicate submissions send one request and freeze fields');
  check(api.calls.at(-1).body.color==='#007AFF'&&api.calls.at(-1).body.permissions[0]==='viewPrivate','Roles: chosen color and permissions are submitted');
  api.reply(500,'<html>synthetic failure</html>',true);await settle();
  check(document.getElementById('role-name').value==='Auditor'&&dialog().querySelector('[aria-label="Hex"]').value==='007AFF'&&dialog().querySelector('[role="alert"]').textContent.includes('HTTP 500'),'Roles: non-JSON error preserves the editor');
  form.requestSubmit();await settle();api.reply(200,[]);await settle();
  check(dialog()&&dialog().querySelector('[role="alert"]').textContent.includes('could not be confirmed'),'Roles: unrelated successful list cannot close the editor');
  form.requestSubmit();await settle();api.reply(200,[...api.roles,{id:'auditor',name:'Auditor',color:'#007AFF',permissions:['viewPrivate']}]);await settle();await waitClosed();
  check(!dialog()&&button(roles,'Auditor'),'Roles: acknowledged save updates the list');
  button(roles,'Auditor').click();await settle();
  count=api.calls.length;api.confirmNext=false;button(dialog(),'Delete role').click();await settle();
  check(api.calls.length===count,'Role deletion: cancellation sends nothing');
  api.confirmNext=true;button(dialog(),'Delete role').click();await settle();api.fail();await settle();
  check(dialog()&&button(roles,'Auditor')&&dialog().querySelector('[role="alert"]'),'Role deletion: network failure preserves role and editor');
  button(dialog(),'Delete role').click();await settle();api.reply(200,api.roles);await settle();await waitClosed();
  check(!dialog()&&!button(roles,'Auditor'),'Role deletion: confirmed removal updates the list');
  return {passed:checks.length,checks,requests:api.calls.length,pending:api.pending.length};
})()
